import type { PlaneMarker, ProjectSettings, SpeedCurveState, Stroke, Waypoint } from '../types';

/** "click.click.......click" -> [0.000, 0.100, 0.700]-style absolute times. */
export function tapsToAbsolute(taps: number[]): string {
  return `[${taps.map((t) => t.toFixed(3)).join(', ')}]`;
}

export function tapsToDeltas(taps: number[]): number[] {
  return taps.slice(1).map((t, i) => t - taps[i]);
}

/** Waypoints -> copy-pasteable Remotion snippet (normalized + px). */
export function waypointsToRemotion(wps: Waypoint[], project: ProjectSettings): string {
  const px = wps.map((w) => ({
    x: Math.round(w.x * project.width),
    y: Math.round(w.y * project.height),
  }));
  return (
    `// ${project.width}x${project.height} @ ${project.fps}fps — generated by remotion-helper\n` +
    `export const waypoints = ${JSON.stringify(wps.map((w) => ({ x: +w.x.toFixed(4), y: +w.y.toFixed(4) })), null, 2)};\n` +
    `export const waypointsPx = ${JSON.stringify(px, null, 2)};\n`
  );
}

export function tapsToRemotion(taps: number[], fps: number): string {
  const frames = taps.map((t) => Math.round(t * fps));
  return (
    `// ${taps.length} taps — seconds + frames @ ${fps}fps\n` +
    `export const tapSeconds = [${taps.map((t) => t.toFixed(3)).join(', ')}];\n` +
    `export const tapFrames = [${frames.join(', ')}];\n`
  );
}

export function speedCurveToRemotion(sc: SpeedCurveState): string {
  const [x1, y1, x2, y2] = sc.bezier;
  return (
    `import { Easing, interpolate } from 'remotion';\n\n` +
    `export const myEasing = Easing.bezier(${x1}, ${y1}, ${x2}, ${y2});\n` +
    `// usage: interpolate(frame, [0, ${Math.round(sc.duration * 30)}], [0, 1], { easing: myEasing });\n`
  );
}

/** CSS cubic-bezier string for the live preview. */
export function bezierToCss(b: SpeedCurveState['bezier']): string {
  return `cubic-bezier(${b.join(', ')})`;
}

/** 3D plane markers -> normalized coords (map x/y onto your plane in Remotion). */
export function markers3DToRemotion(markers: PlaneMarker[]): string {
  return (
    `// ${markers.length} 3D-plane marker(s) — x,y normalized 0..1, y-down like 2D\n` +
    `export const planeMarkers = ${JSON.stringify(
      markers.map((m) => ({ x: m.x, y: m.y })),
      null,
      2,
    )};\n`
  );
}

/** Freehand strokes -> px path + per-point seconds, replayable at recorded speed. */
export function strokesToRemotion(strokes: Stroke[], project: ProjectSettings, fps: number): string {
  const out = strokes.map((s) => ({
    label: s.label,
    duration: s.points.length ? +s.points[s.points.length - 1].t.toFixed(3) : 0,
    frames: s.points.length ? Math.round(s.points[s.points.length - 1].t * fps) : 0,
    path: s.points.map((p) => ({
      x: Math.round(p.x * project.width),
      y: Math.round(p.y * project.height),
      t: +p.t.toFixed(3),
    })),
  }));
  return (
    `// ${strokes.length} stroke(s) — px path with per-point seconds @ ${fps}fps\n` +
    `// replay: find segment where t matches frame/fps, lerp x/y\n` +
    `export const strokes = ${JSON.stringify(out, null, 2)};\n`
  );
}
